"""AgentLoop main loop: plan → act → observe (contract §1.3; ARCHITECTURE §4)."""

from __future__ import annotations

import json
from collections.abc import Callable
from datetime import datetime, timezone
from typing import Any
from uuid import uuid4

from src.agent.events import EventLog
from src.agent.llm import LLMClientProtocol, Message
from src.agent.registry import ToolRegistry
from src.config import Settings
from src.models.agent_result import AgentResult
from src.models.events import AgentEvent, AgentEventType

_SYSTEM_PROMPT = (
    "You are an agent that executes multi-step tasks. Available tools are provided via the tools parameter. Call a tool whenever external capability is needed."
    "Tool failures come back as tool results prefixed with ERROR:. Retry with different arguments or change strategy."
    "Once the goal is achieved, give the final answer text directly and stop calling tools."
)

_SUMMARY_LIMIT = 512


class AgentLoop:
    """Single-task main loop (M1: no persistence, no recovery semantics; events go to JSONL)."""

    def __init__(
        self,
        client: LLMClientProtocol,
        registry: ToolRegistry,
        settings: Settings,
        on_event: Callable[[AgentEvent], None] | None = None,
        task_id: str | None = None,
    ) -> None:
        """task_id may be pre-generated by the caller (CLI) so stdout prints early and matches the event file name."""
        self._client = client
        self._registry = registry
        self._settings = settings
        self._on_event = on_event
        self._task_id = task_id if task_id is not None else f"task-{uuid4().hex[:12]}"

    async def run_task(self, goal: str) -> AgentResult:
        """Run the task and return the full result (events are flushed to JSONL before continuing)."""
        log = EventLog(self._task_id)
        events: list[AgentEvent] = []
        seq = 0

        def emit(event_type: AgentEventType, payload: dict[str, object]) -> AgentEvent:
            nonlocal seq
            seq += 1
            event = AgentEvent(
                type=event_type,
                seq=seq,
                ts=datetime.now(timezone.utc),
                payload=payload,
            )
            log.append(event)  # events hit disk before the loop continues (contract §1.3.6)
            events.append(event)
            if self._on_event is not None:
                self._on_event(event)
            return event

        emit(AgentEventType.status, {"status": "running", "reason": "task started"})

        messages: list[Message] = [
            {"role": "system", "content": _SYSTEM_PROMPT},
            {"role": "user", "content": goal},
        ]
        steps = 0
        status = "completed"
        result_text = ""

        while True:
            if steps >= self._settings.calc_agent_max_steps:
                status = "failed"
                result_text = "max steps exceeded"
                emit(AgentEventType.error, {"message": "max steps exceeded"})
                break
            try:
                response = await self._client.chat(messages, self._registry.get_schemas())
            except (AssertionError, KeyboardInterrupt, SystemExit):
                # test assertions and interrupt signals pass through, never swallowed into failed
                raise
            except Exception as exc:  # retries exhausted / LLMProtocolError → unrecoverable
                status = "failed"
                result_text = f"llm error: {type(exc).__name__}: {exc}"
                emit(AgentEventType.error, {"message": result_text[:_SUMMARY_LIMIT]})
                break

            steps += 1

            if not response.tool_calls:
                # the model gives its final answer; content produces no event (ADR-006)
                status = "completed"
                result_text = response.content
                break

            native_calls: list[dict[str, Any]] = []
            for call in response.tool_calls:
                native: dict[str, Any] = {
                    "id": call.remote_id,
                    "type": "function",
                    "function": {
                        "name": call.tool_name,
                        "arguments": json.dumps(call.arguments, ensure_ascii=False),
                    },
                }
                if call.provider_extra is not None:
                    # opaque provider extension (e.g. Gemini 3.x thought_signature) —
                    # echoed back verbatim; providers without it stay byte-identical
                    native["extra_content"] = call.provider_extra
                native_calls.append(native)
            messages.append(
                {"role": "assistant", "content": response.content, "tool_calls": native_calls}
            )

            for call in response.tool_calls:
                # tool_call_id = the seq of this tool_call event (contract §1.3.2, event-sequence scheme)
                next_seq = seq + 1
                tool_call_id = f"call_{next_seq:04d}"
                args_summary = json.dumps(call.arguments, ensure_ascii=False)
                emit(
                    AgentEventType.tool_call,
                    {
                        "tool_call_id": tool_call_id,
                        "tool_name": call.tool_name,
                        "args_summary": args_summary[:_SUMMARY_LIMIT],
                    },
                )
                tool_result = await self._registry.execute(call.tool_name, call.arguments)
                summary = tool_result.result if tool_result.ok else tool_result.error
                emit(
                    AgentEventType.tool_result,
                    {
                        "tool_call_id": tool_call_id,
                        "ok": tool_result.ok,
                        "result_summary": summary[:_SUMMARY_LIMIT],
                    },
                )
                tool_content = (
                    tool_result.result if tool_result.ok else f"ERROR: {tool_result.error}"
                )
                messages.append(
                    {"role": "tool", "tool_call_id": call.remote_id, "content": tool_content}
                )

        # final is always emitted (on every termination path)
        emit(
            AgentEventType.final,
            {"status": status, "result_summary": result_text[:_SUMMARY_LIMIT]},
        )
        return AgentResult(
            task_id=self._task_id,
            status=status,
            result=result_text,
            steps=steps,
            events=events,
        )
